import type {PermissionOwner, PermissionRequest, PermissionDecision} from '../../../shared/xiaozhi-permissions';
import type {TerminalJobView} from '../../../shared/xiaozhi-terminal-jobs';
import type {ExecutionProjection} from '../permissions/windows/projection';
import type {ToolContractReceipt} from '../capabilities/core-governance';

export type JobActor = {kind: 'teacher'; sessionId: string} | {kind: 'agent'; owner: PermissionOwner};
export type JobController = {kind: 'teacher'} | {kind: 'agent'; owner: PermissionOwner};
export type TerminalJobDocument = {
  schemaVersion: 1;
  jobId: string;
  sessionId: string;
  taskId: string;
  revision: number;
  controllerRevision: number;
  leaseRevision: number;
  origin: PermissionOwner;
  callId: string;
  effectId: string;
  contract: ToolContractReceipt;
  controller: JobController;
  blockedAgent?: PermissionOwner;
  request: PermissionRequest;
  decision: PermissionDecision;
  runtime: {version: string; directory: string; helperHash: string};
  projection: ExecutionProjection;
  command: string;
  cwd: string;
  state: 'starting' | 'running' | 'completed' | 'failed' | 'cancelled' | 'timed_out' | 'interrupted';
  tty: boolean;
  background: boolean;
  createdAt: string;
  updatedAt: string;
  expiresAt: string;
  inputClosed: boolean;
  cleanup: TerminalJobView['cleanup'];
  notice?: TerminalJobView['notice'];
  exitCode?: number;
  durationMs?: number;
  pid?: number;
  helperPid?: number;
  committed: string[];
  projectionState: 'pending' | 'committed' | 'needs_check';
};
export type TerminalJobRecord = {
  document: TerminalJobDocument;
  inputSequence: number;
  acknowledgedInputSequence: number;
  outputSequence: number;
  output: string;
  outputBytes: number;
  truncated: boolean;
};
