import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { chatCompletionsUrl } from '../src/main/ai-provider-endpoint.ts';

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const dataRoot = mkdtempSync(join(tmpdir(), 'omni-edu-provider-'));
const env = { ...process.env, DEEPSEEK_API_KEY: '', GLM_API_KEY: '', OMNI_EDU_DATA_ROOT: dataRoot, OMNI_EDU_E2E_DIALOG_MODE: '1' };
let app;
try {
  assert.equal(chatCompletionsUrl('deepseek'), 'https://api.deepseek.com/chat/completions');
  assert.equal(chatCompletionsUrl('glm'), 'https://open.bigmodel.cn/api/paas/v4/chat/completions');
  app = await electron.launch({ args: [join(appRoot, 'out/main/index.js')], cwd: appRoot, env });
  let page = await app.firstWindow();
  await page.waitForFunction(() => Boolean(window.omniEdu));
  await page.getByTestId('ai-return-workspace').click();
  await page.getByTestId('nav-settings').click();
  await page.getByTestId('ai-provider-select').selectOption('deepseek');
  await page.getByTestId('ai-provider-api-key').fill('test-deepseek-credential-12345678');
  await page.getByTestId('ai-provider-save').click();
  let settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'deepseek');
  assert.equal(settings.providers.deepseek.configured, true);
  assert.equal(JSON.stringify(settings).includes('test-deepseek-credential'), false, 'API key must not be exposed to renderer');

  await page.getByTestId('ai-provider-select').selectOption('glm');
  assert.equal(await page.getByTestId('ai-provider-model').inputValue(), 'glm-4.5-air');
  await page.getByTestId('ai-provider-save').click();
  settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'glm');
  assert.equal(settings.configured, false);
  assert.equal(settings.providers.deepseek.configured, true, 'selecting GLM must retain DeepSeek credentials');
  await page.getByTestId('nav-ai').click();
  await page.getByTestId('ai-prompt-input').fill('你好');
  await page.getByRole('button', { name: '运行 GLM' }).click();
  await page.getByTestId('ai-output-error').waitFor({ state: 'visible' });
  assert.match(await page.getByTestId('ai-output-error').textContent(), /智谱 GLM API Key/);
  assert.equal(await page.getByTestId('ai-prompt-input').inputValue(), '');

  await page.getByTestId('ai-return-workspace').click();
  await page.getByTestId('nav-settings').click();
  await page.getByTestId('ai-provider-api-key').fill('test-glm-credential-12345678');
  await page.getByTestId('ai-provider-save').click();
  settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'glm');
  assert.equal(settings.configured, true);
  assert.equal(JSON.stringify(settings).includes('test-glm-credential'), false);
  await page.getByTestId('nav-ai').click();
  await page.getByTestId('ai-prompt-input').fill('你好');
  await page.getByRole('button', { name: '运行 GLM' }).click();
  await page.waitForFunction(() => document.querySelectorAll('[data-testid="ai-output-error"]').length >= 2, undefined, { timeout: 60_000 });
  const liveGlmError = await page.getByTestId('ai-output-error').last().textContent();
  assert.doesNotMatch(liveGlmError ?? '', /缺少.*API Key|TypeError: fetch failed/);
  assert.equal(await page.getByTestId('ai-prompt-input').inputValue(), '');
  await page.getByTestId('ai-prompt-input').fill('请为教师设计一段错题练习建议');
  await page.getByRole('button', { name: '运行 GLM' }).click();
  await page.waitForFunction(() => document.querySelectorAll('[data-testid="ai-output-error"]').length >= 3, undefined, { timeout: 130_000 });
  const structuredGlmError = await page.getByTestId('ai-output-error').last().textContent();
  assert.doesNotMatch(structuredGlmError ?? '', /缺少.*API Key|TypeError: fetch failed/);
  await app.close();

  app = await electron.launch({ args: [join(appRoot, 'out/main/index.js')], cwd: appRoot, env });
  page = await app.firstWindow();
  await page.waitForFunction(() => Boolean(window.omniEdu));
  settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'glm', 'selected provider must survive restart');
  assert.equal(settings.providers.glm.configured, true);
  assert.equal(settings.providers.deepseek.configured, true);
  await page.waitForFunction(() => document.querySelector('[data-testid="ai-composer-provider"]')?.value === 'glm');
  await page.getByTestId('ai-composer-provider').selectOption('deepseek');
  await page.waitForFunction(async () => (await window.omniEdu.getDeepSeekSettings()).provider === 'deepseek');
  await page.waitForFunction(() => document.querySelector('[data-testid="ai-composer-provider"]')?.value === 'deepseek');
  await page.getByTestId('ai-return-workspace').click();
  await page.getByTestId('nav-settings').click();
  await page.waitForFunction(() => document.querySelector('[data-testid="ai-provider-select"]')?.value === 'deepseek');
  assert.equal(await page.getByTestId('ai-provider-select').inputValue(), 'deepseek', 'composer selection must update settings view');
  await page.getByTestId('ai-provider-save').click();
  await page.waitForFunction(async () => (await window.omniEdu.getDeepSeekSettings()).provider === 'deepseek');
  settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'deepseek');
  assert.equal(settings.configured, true, 'blank edit must preserve the selected provider key');
  assert.equal(settings.providers.glm.configured, true, 'switching back must preserve GLM key');
  await app.close();
  const legacyDb = new DatabaseSync(join(dataRoot, 'app.db'));
  legacyDb.prepare("DELETE FROM app_settings WHERE key = 'ai_provider_selected'").run();
  legacyDb.close();
  app = await electron.launch({ args: [join(appRoot, 'out/main/index.js')], cwd: appRoot, env });
  page = await app.firstWindow();
  await page.waitForFunction(() => Boolean(window.omniEdu));
  settings = await page.evaluate(() => window.omniEdu.getDeepSeekSettings());
  assert.equal(settings.provider, 'deepseek', 'old database without provider selection defaults to DeepSeek');
  assert.equal(settings.configured, true);
  console.log(JSON.stringify({ suite: 'ai-provider-electron', passed: true, directGlmAuthError: (liveGlmError ?? '').slice(0, 120), structuredGlmAuthError: (structuredGlmError ?? '').slice(0, 120), checks: 'official endpoints, settings and composer selection, isolated credentials, missing-GLM fail closed, direct and structured GLM HTTP request, restart readback, blank edit retains key, legacy selection fallback' }));
} finally {
  await app?.close().catch(() => undefined);
  rmSync(dataRoot, { recursive: true, force: true, maxRetries: 5, retryDelay: 150 });
}
