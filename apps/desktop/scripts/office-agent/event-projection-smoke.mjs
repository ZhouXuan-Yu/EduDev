import assert from 'node:assert/strict';
import { createOfficeProjection, ingestOfficeNotification, hydrateOfficeProjection, beginOfficeConnection, projectOfficeItem } from '../../src/main/office-agent/event-projection.ts';
const state = createOfficeProjection('thread-test', 'deepseek-flash');
let sequence = 0;
const apply = (method, params) => ingestOfficeNotification(state, 1, ++sequence, { method, params: { threadId: 'thread-test', turnId: 'turn-test', ...params } });
apply('item/started', { item: { type: 'agentMessage', id: 'message-test', text: '', phase: 'final_answer' } });
apply('item/agentMessage/delta', { itemId: 'message-test', delta: '先读取' });
apply('item/agentMessage/delta', { itemId: 'message-test', delta: '文件。' });
apply('item/completed', { item: { type: 'agentMessage', id: 'message-test', text: '先读取文件。', phase: 'commentary' } });
assert.equal(state.turns[0].items.length, 1);
assert.equal(state.turns[0].items[0].text, '先读取文件。');
assert.equal(state.turns[0].items[0].phase, 'commentary');
const beforeDuplicate = JSON.stringify(state);
assert.equal(ingestOfficeNotification(state, 1, sequence, { method: 'item/agentMessage/delta', params: { threadId: 'thread-test', turnId: 'turn-test', itemId: 'message-test', delta: '重复' } }), false);
assert.equal(JSON.stringify(state), beforeDuplicate);
apply('item/completed', { item: { type: 'reasoning', id: 'private-item', summary: ['PRIVATE-SUMMARY-SENTINEL'], content: ['HIDDEN-CONTENT-SENTINEL'] } });
apply('item/reasoning/textDelta', { itemId: 'private-item', delta: 'HIDDEN-DELTA-SENTINEL' });
apply('unknown/private', { secret: 'UNKNOWN-SENTINEL' });
assert.doesNotMatch(JSON.stringify(state), /SENTINEL/);
apply('item/completed', { item: { type: 'dynamicToolCall', id: 'tool-test', tool: 'office_read_text', status: 'completed', durationMs: 34,
  arguments: { path: 'private.env' }, contentItems: [{ type: 'inputText', text: 'TOOL-RAW-SENTINEL' }], success: true } });
assert.doesNotMatch(JSON.stringify(state), /private.env|TOOL-RAW-SENTINEL|arguments|contentItems/);
assert.equal(state.turns[0].items[1].durationMs, 34);
apply('turn/completed', { turn: { id: 'turn-test', status: 'interrupted', error: null } });
const terminalItems = structuredClone(state.turns[0].items);
apply('item/agentMessage/delta', { itemId: 'message-test', delta: '迟到内容' });
apply('item/started', { item: { type: 'agentMessage', id: 'late-new-item', text: 'LATE', phase: 'final_answer' } });
assert.equal(state.turns[0].status, 'interrupted');
assert.deepEqual(state.turns[0].items, terminalItems);
const gapState = createOfficeProjection('thread-test', 'deepseek-flash');
assert.equal(ingestOfficeNotification(gapState, 1, 2, { method: 'unknown' }), false);
assert.equal(gapState.needsHydration, true);
assert.equal(gapState.sourceSequence, 0);
const reconnected = beginOfficeConnection(state);
assert.equal(ingestOfficeNotification(reconnected, 1, 99, { method: 'unknown' }), false);
const response = { thread: { id: 'thread-test', modelProvider: 'deepseek', model: 'deepseek-flash', turns: [{ id: 'turn-test', status: 'interrupted', itemsView: 'summary', items: [] }] } };
assert.equal(hydrateOfficeProjection(reconnected, 2, 0, response), false);
assert.deepEqual(reconnected.turns, state.turns, 'Partial reads must not erase history');
response.thread.turns[0].itemsView = 'full';
response.thread.turns[0].items = [{ type: 'agentMessage', id: 'message-test', text: '恢复后的正文', phase: 'final_answer' }];
assert.equal(hydrateOfficeProjection(reconnected, 2, 0, response), true);
assert.equal(reconnected.needsHydration, false);
assert.equal(reconnected.turns[0].items[0].text, '恢复后的正文');
assert.throws(() => hydrateOfficeProjection(reconnected, 2, 0, { thread: { ...response.thread, modelProvider: 'other' } }), /snapshot mismatch/);
const bounded = projectOfficeItem({ type: 'agentMessage', id: 'large', text: '中'.repeat(100000), phase: 'final_answer' });
assert.equal(bounded.text.length, 65536); assert.equal(bounded.truncated, true);
assert.doesNotMatch(projectOfficeItem({ type: 'agentMessage', id: 'secret', text: 'sk-abcdefghijklmnopqrstuvwxyz012345', phase: 'final_answer' }).text, /abcdefghijklmnopqrstuvwxyz/);
assert.equal(projectOfficeItem({ type: 'agentMessage', id: 'malformed' }), undefined);
console.log(JSON.stringify({ suite: 'office-event-boundary-and-recovery', success: true,
  cases: ['delta-completed-upsert', 'canonical-phase', 'duplicate-sequence', 'hidden-content-omitted', 'tool-output-omitted',
    'late-terminal-events', 'sequence-gap', 'old-epoch', 'partial-history', 'full-history', 'provider-snapshot', 'text-budget', 'key-redaction', 'malformed-item'] }));
