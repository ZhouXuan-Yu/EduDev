// Reuse the exact official generated protocol, retaining only the import closure we consume.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, relative, dirname, join, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { resolveCodexRuntime, CODEX_VERSION } from './codex-runtime.mjs';
const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourceRoot = join(appRoot, 'test-results/office-plan/codex-protocol-locked');
const targetRoot = join(appRoot, 'src/main/office-agent/vendor/codex-protocol');
mkdirSync(sourceRoot, { recursive: true });
execFileSync(resolveCodexRuntime().binaryPath, ['app-server', 'generate-ts', '--experimental', '--out', sourceRoot], { windowsHide: true });
const queue = ['v2/ThreadReadResponse.ts', 'v2/ThreadItem.ts', 'v2/TurnCompletedNotification.ts',
  'v2/AgentMessageDeltaNotification.ts', 'v2/ItemStartedNotification.ts', 'v2/ItemCompletedNotification.ts',
  'InitializeParams.ts', 'InitializeResponse.ts', 'v2/ThreadStartParams.ts', 'v2/ThreadStartResponse.ts',
  'v2/ThreadResumeParams.ts', 'v2/ThreadResumeResponse.ts', 'v2/ThreadReadParams.ts',
  'v2/TurnStartParams.ts', 'v2/TurnStartResponse.ts', 'v2/TurnInterruptParams.ts', 'v2/TurnInterruptResponse.ts',
  'v2/DynamicToolCallParams.ts', 'v2/DynamicToolCallResponse.ts'];
const visited = new Set();
while (queue.length) {
  const filename = queue.shift(); if (visited.has(filename)) continue;
  const path = resolve(sourceRoot, filename); const within = relative(sourceRoot, path);
  if (isAbsolute(within) || within.startsWith('..')) throw new Error('Generated type import escapes source root');
  const content = readFileSync(path, 'utf8');
  const target = join(targetRoot, filename); mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content); visited.add(filename);
  for (const match of content.matchAll(/from\s+["']([^"']+)["']/g)) {
    if (!match[1].startsWith('.')) throw new Error('Unexpected external generated type dependency');
    queue.push(relative(sourceRoot, resolve(dirname(path), `${match[1]}.ts`)));
  }
}
writeFileSync(join(targetRoot, 'README.md'), `# Official Codex generated protocol\n\nGenerated by locked Codex ${CODEX_VERSION} with app-server generate-ts --experimental. Apache-2.0; license/notice: third_party/codex. Do not hand edit. Import closure: ${visited.size} files. Regenerate with node scripts/office-agent/sync-protocol-types.mjs and verify the runtime contract before updating.\n`);
console.log(JSON.stringify({ suite: 'official-protocol-import-closure', version: CODEX_VERSION, files: visited.size }));
